function moderate(text) {
  const t = norm(text);
  if (RX.ad.some(r => r.test(t) || r.test(text))) return 'ad';
  if (RX.medical.some(r => r.test(t))) return 'medical';
  if (RX.risk.some(r => r.test(t))) return 'risk';
  return 'ok';
}
